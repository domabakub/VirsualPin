const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/Asus/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
async function main() {
  const out = path.resolve('docs/ranat-hand-play'); fs.mkdirSync(out,{recursive:true});
  const browser = await chromium.launch({channel:'msedge',headless:true,args:['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--autoplay-policy=no-user-gesture-required']});
  const context = await browser.newContext({viewport:{width:1440,height:1100},permissions:['camera']});
  const page = await context.newPage(), errors=[], failedRequests=[];
  page.on('response',r=>{if(r.status()>=400)failedRequests.push({url:r.url(),status:r.status()});});
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('console',m=>{if(m.type()==='error')errors.push({message:m.text(),location:m.location()});});
  try {
    await page.goto('http://localhost:3000/instruments/ranat/play',{waitUntil:'networkidle',timeout:90000});
    await page.locator('canvas[aria-label="โมเดลระนาดเอกสามมิติ"]').waitFor({timeout:60000});
    await page.waitForTimeout(2000);
    await page.screenshot({path:path.join(out,'touch-desktop.png'),fullPage:true});
    await page.getByRole('button',{name:'อัดทำนอง',exact:true}).click();
    await page.getByRole('button',{name:'ลา ลูก 1',exact:true}).click();
    await page.keyboard.press('a'); await page.keyboard.press('s');
    await page.getByRole('button',{name:'หยุดและบันทึก',exact:true}).click();
    const takes=await page.evaluate(()=>JSON.parse(localStorage.getItem('next-instruments.ranat.takes.v1')||'[]'));
    if(takes[0]?.events.length!==3)throw new Error(`Expected three notes, got ${takes[0]?.events.length}`);
    await page.getByRole('button',{name:'อัดทำนอง',exact:true}).click();
    const model=await page.locator('canvas[aria-label="โมเดลระนาดเอกสามมิติ"]').boundingBox();
    await page.mouse.click(model.x+model.width*.5,model.y+model.height*.48);
    const a=await page.getByRole('button',{name:'ลา ลูก 1',exact:true}).boundingBox();
    const b=await page.getByRole('button',{name:'โด ลูก 3',exact:true}).boundingBox();
    const cdp=await context.newCDPSession(page);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:1,x:a.x+a.width/2,y:a.y+a.height/2},{id:2,x:b.x+b.width/2,y:b.y+b.height/2}]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    await page.getByRole('button',{name:'หยุดและบันทึก',exact:true}).click();
    const pointerNotes=await page.evaluate(()=>JSON.parse(localStorage.getItem('next-instruments.ranat.takes.v1'))[0].events);
    if(pointerNotes.length!==3)throw new Error(`Expected model hit + two-finger chord, got ${pointerNotes.length}`);
    await page.getByRole('button',{name:/^ฟัง ทำนอง/}).first().click();
    await page.waitForTimeout(600);
    await page.screenshot({path:path.join(out,'playback-desktop.png'),fullPage:true});
    await page.getByRole('button',{name:'หยุดฟัง',exact:true}).click();
    await page.getByRole('button',{name:/กล้อง/}).first().click();
    await page.getByRole('heading',{name:'มือขยับ. ไม้ตาม.'}).waitFor();
    await page.screenshot({path:path.join(out,'camera-desktop.png'),fullPage:true});
    await page.getByRole('button',{name:'เปิดกล้อง',exact:true}).click();
    await page.waitForTimeout(12000);
    const trackerText=await page.locator('.rn-air-workspace').innerText();
    await page.getByRole('button',{name:'เริ่มจับมือ',exact:true}).click();
    await page.waitForTimeout(600);
    if(!await page.getByRole('button',{name:'พักการจับมือ',exact:true}).isVisible())throw new Error('Hand play did not start');
    await page.getByRole('button',{name:'พักการจับมือ',exact:true}).click();
    await page.getByRole('button',{name:'ตั้งพื้นที่เล่น',exact:true}).click();
    await page.getByRole('button',{name:'จับตำแหน่งใน 2 วินาที',exact:true}).click();
    await page.waitForTimeout(2200);
    if(!await page.getByText('ให้กล้องเห็นมือเดียวชัด ๆ แล้วจับตำแหน่งอีกครั้ง').isVisible())throw new Error('Empty calibration was accepted');
    await page.getByRole('button',{name:'ยกเลิก',exact:true}).click();
    await page.screenshot({path:path.join(out,'camera-open.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(1000);
    await page.screenshot({path:path.join(out,'camera-mobile.png'),fullPage:true});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    if(overflow)throw new Error('Mobile page overflows horizontally');
    await page.getByRole('button',{name:'สัมผัส / คีย์บอร์ด',exact:true}).click();
    await page.getByRole('button',{name:'ใช้ภาพ 2D',exact:true}).click();
    await page.locator('svg.rn-instrument').waitFor();
    await page.screenshot({path:path.join(out,'fallback-mobile.png'),fullPage:true});
    await page.goto('http://localhost:3000/instruments',{waitUntil:'networkidle'});
    await page.locator('.rn-model-showcase').scrollIntoViewIfNeeded();
    await page.locator('.rn-model-showcase canvas').waitFor();await page.waitForTimeout(1200);
    await page.screenshot({path:path.join(out,'showcase-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1000});await page.waitForTimeout(700);
    await page.screenshot({path:path.join(out,'showcase-desktop.png'),fullPage:true});
    const report={recordedNotes:takes[0].events.map(e=>({bar:e.bar,source:e.source})),pointerNotes:pointerNotes.map(e=>e.bar),mobileOverflow:overflow,trackerText,errors,failedRequests};
    fs.writeFileSync(path.join(out,'browser-report.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify(report,null,2));
  } finally {await browser.close();}
}
main().catch(e=>{console.error(e);process.exitCode=1;});
